def get_queue_info(queue_id: int) -> str:
    """
    Riot API queueId를 한글 큐 이름으로 변환합니다.
    
    Args:
        queue_id: Riot API에서 제공하는 queueId
        
    Returns:
        한글 큐 명칭
    """
    queue_map = {
        0: "커스텀",
        400: "일겜", # 일반(교차 선택)
        420: "솔랭",
        430: "일겜", # 일반(비공개 선택)
        440: "자랭",
        450: "칼바람", # 무작위 총력전(칼바람)
        480: "신속", #신속 대전
        490: "일겜", # 일반(빠른 대전)
        700: "격전",
        830: "AI 상대 대전(입문)",
        840: "AI 상대 대전(초보)",
        850: "AI 상대 대전(중급)",
        900: "URF",
        1020: "단일모드", # 단일 챔피언
        1300: "돌아온 돌거북",
        1400: "궁극기 주문서",
        1700: "아레나",
        1900: "URF",
        2000: "튜토리얼 1",
        2010: "튜토리얼 2",
        2020: "튜토리얼 3",
        2400: "증바람", # 무작위 총력전(증강)
    }
    
    return queue_map.get(queue_id, f"기타({queue_id})")
